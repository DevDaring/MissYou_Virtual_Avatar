function Support() {
  const q = useQuery({ queryKey: ['support'], queryFn: () => get<SupportResources>('/api/support'), staleTime: 3_600_000 })
  return (
    <div className="space-y-5">
      <div className="rounded-2xl bg-red-500/10 px-4 py-4 ring-1 ring-red-400/30" role="note">
        <p className="font-semibold text-red-100">If you are in danger right now, call <a className="underline" href="tel:112">112</a>.</p>
      </div>
      <section className="card space-y-3">
        <h2 className="text-xl">{q.data?.title || "You don't have to go through this alone"}</h2>
        {q.isLoading && <Spinner />}
        {q.isError && <Notice tone="error">{errorText(q.error)}</Notice>}
        <SupportList res={q.data} />
      </section>
      <section className="card space-y-2">
        <h2 className="text-xl">About grief</h2>
        <p className="leading-relaxed text-cream-100/85">
          Grief has no timetable. Some days a call may feel comforting; other days it may not, and that's okay. Talking with friends, family, a support group or a counsellor can help in ways an app can't. Miss You is one small place to remember — not a replacement for the people around you.
        </p>
      </section>
    </div>
  )
}

export default function Legal({ page }: { page: Page }) {
  const nav = useNavigate()
  const canBack = typeof window !== 'undefined' && ((window.history.state as { idx?: number } | null)?.idx ?? 0) > 0
  useEffect(() => {
    document.title = `${TITLES[page]} · Miss You`
    window.scrollTo(0, 0)
  }, [page])

  return (
    <div className="relative min-h-screen pb-16">
      <div className="pointer-events-none fixed inset-0 -z-10 bg-[radial-gradient(ellipse_at_top,rgba(143,122,214,0.16),transparent_60%)]" aria-hidden="true" />
      <header className="border-b border-white/5 bg-night-900/80 backdrop-blur">
        <div className="mx-auto flex h-16 max-w-3xl items-center justify-between gap-3 px-4">
          <Link to="/" aria-label="Miss You home" className="flex items-center"><Logo size={30} withWordmark /></Link>
          {canBack ? (
            <button className="inline-flex min-h-[48px] items-center gap-1 rounded-full px-3 text-sm font-semibold text-cream-200/80 hover:text-cream-50" onClick={() => nav(-1)}>
              <span aria-hidden="true">←</span> Back
            </button>
          ) : (
            <Link className="inline-flex min-h-[48px] items-center gap-1 rounded-full px-3 text-sm font-semibold text-cream-200/80 hover:text-cream-50" to="/">
              <span aria-hidden="true">←</span> Back
            </Link>
          )}
        </div>
      </header>
      <main className="mx-auto max-w-3xl px-4 pt-8">
        <h1 className="mb-6 text-3xl leading-tight sm:text-4xl">{TITLES[page]}</h1>
        {page === 'terms' && <Terms />}
        {page === 'privacy' && <Privacy />}
        {page === 'faq' && <Faq />}
        {page === 'support' && <Support />}
        <nav aria-label="More pages" className="mt-10 flex flex-wrap gap-2 border-t border-white/10 pt-6">
          {(['faq', 'support', 'terms', 'privacy'] as Page[]).map((p) => (
            <NavLink key={p} to={`/${p}`} className={({ isActive }) => `inline-flex min-h-[48px] items-center rounded-full px-4 text-sm font-semibold ring-1 ${isActive ? 'bg-white/10 text-cream-50 ring-white/20' : 'text-cream-200/75 ring-white/10 hover:text-cream-50'}`}>
              {TITLES[p]}
            </NavLink>
          ))}
        </nav>
      </main>
    </div>
  )
}

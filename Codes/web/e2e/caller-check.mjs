// "Who's calling?" flow in the browser as the jury: add a caller, edit them, call as them, then remove them.
import { chromium } from 'playwright-core'
import os from 'os'
const B = 'https://missyou.koushikdeb.com'
const b = await chromium.launch({ executablePath: `${os.homedir()}/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome`, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required'] })
const page = await (await b.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['microphone'] })).newPage()
const errs = []; page.on('pageerror', (e) => errs.push(String(e)))
page.on('websocket', (ws) => ws.on('framereceived', (f) => { const m = JSON.parse(String(f.payload)); if (m.type === 'reply_text' || m.type === 'subtitle') console.log(m.type, '→', m.text) }))
await page.goto(`${B}/login?jury=1`); await page.getByRole('button', { name: 'Sign in', exact: true }).click(); await page.waitForURL('**/home')
await page.getByRole('link', { name: 'Open details' }).first().click(); await page.waitForURL('**/people/**')
await page.getByRole('button', { name: /Someone else is calling/ }).click()
const plus = page.getByRole('button', { name: '+ Someone else' }); if (await plus.count()) await plus.click()
await page.getByLabel('Their name').fill('Mitali')
await page.getByLabel(/is their…/).fill('elder sister')
await page.getByLabel(/called them/).fill('ছোটো')
await page.getByLabel(/What they call/).fill('Didi')
await page.getByLabel(/Things they shared/).fill('Grew up together in Barasat; their mother\'s shorshe ilish; the Durga Puja dhunuchi dance contests they always argued about winning')
await page.getByRole('button', { name: 'Save', exact: true }).click()
await page.getByRole('button', { name: 'Edit Mitali' }).click()
await page.getByLabel(/What they call/).fill('Didibhai'); await page.getByRole('button', { name: 'Save', exact: true }).click()
await page.screenshot({ path: `${process.argv[2]}/caller-picker.png` })
await page.getByRole('button', { name: /^Mitali/ }).click()
await page.waitForURL('**/call/**'); await page.getByText('talking with Mitali').waitFor()
await page.waitForTimeout(9000)
await page.getByRole('button', { name: /^(Type|লিখুন|लिखें)$/ }).click()
await page.getByLabel('Message').fill('Didi, remember the dhunuchi dance at Puja? I still say I won!')
await page.getByRole('button', { name: 'Send' }).click(); await page.waitForTimeout(12000)
await page.screenshot({ path: `${process.argv[2]}/caller-call.png` })
await page.getByRole('button', { name: /End call|কল শেষ/ }).dblclick(); await page.waitForTimeout(1500)
await page.goBack(); await page.goto(page.url().includes('/people/') ? page.url() : `${B}/home`)
await page.goto(`${B}/home`); await page.getByRole('link', { name: 'Open details' }).first().click(); await page.waitForURL('**/people/**')
await page.getByRole('button', { name: /Someone else is calling/ }).click(); await page.getByRole('button', { name: 'Remove Mitali' }).click(); await page.waitForTimeout(1200)
console.log('errors', JSON.stringify(errs))
await b.close()
